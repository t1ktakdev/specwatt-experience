import fs from "node:fs/promises";
import { format } from "prettier";
const tokens = JSON.parse(await fs.readFile("design-tokens.json", "utf8"));
const vars = {};
function walk(value, path = []) {
  if (value?.$value !== undefined) {
    const v = value.$value;
    vars[path.join("-")] =
      typeof v === "string"
        ? v
        : Array.isArray(v)
          ? v.join(", ")
          : `${v.value}${v.unit}`;
  } else if (value && typeof value === "object" && !Array.isArray(value)) {
    for (const [key, v] of Object.entries(value))
      if (!key.startsWith("$")) walk(v, [...path, key]);
  }
}
walk(tokens);
for (const [name, style] of Object.entries(tokens.typography)) {
  for (const [property, value] of Object.entries(style)) {
    const kebab = property.replace(
      /[A-Z]/g,
      (char) => "-" + char.toLowerCase(),
    );
    vars[`type-${name}-${kebab}`] =
      property === "fontSize" ? `${value}px` : String(value);
  }
}
const aliases = {
  bg: "color-surface-canvas",
  surface: "color-surface-raised",
  elevated: "color-surface-elevated",
  white: "color-text-primary",
  muted: "color-text-secondary",
  amber: "color-accent-amber",
  "amber-bright": "color-accent-amberBright",
  green: "color-status-protected",
  radius: "radius-card",
};
const css = `/* Generated by npm run tokens. Edit design-tokens.json. */\n:root {\n${Object.entries(
  vars,
)
  .map(([k, v]) => `  --${k}: ${v};`)
  .join("\n")}\n${Object.entries(aliases)
  .map(([k, v]) => `  --${k}: var(--${v});`)
  .join("\n")}\n}\n`;
await fs.writeFile("src/tokens.css", await format(css, { parser: "css" }));
await fs.mkdir("native", { recursive: true });
await fs.writeFile(
  "native/tokens.ts",
  await format(
    `// Generated by npm run tokens. Do not edit.\nexport const tokens = ${JSON.stringify(tokens, null, 2)} as const;\nexport const palette = ${JSON.stringify(Object.fromEntries(Object.entries(tokens.color).flatMap(([group, vals]) => Object.entries(vals).map(([name, v]) => [`${group}${name[0].toUpperCase()}${name.slice(1)}`, v.$value]))), null, 2)} as const;\n`,
    { parser: "typescript" },
  ),
);
console.log(
  `Generated ${Object.keys(vars).length} CSS tokens and native palette.`,
);
